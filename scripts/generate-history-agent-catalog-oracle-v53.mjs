// Freeze the literal pre-V53 Panel collectors as a differential oracle.
// Only finite selected source fragments are parsed; the full Panel is read
// and pinned as bytes, never sent to a whole-file AST/type program.
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { stripTypeScriptTypes } from 'node:module';
import { fileURLToPath } from 'node:url';
const expectedSourceSHA = '9b61ffee0592c8148e285600a72aedb4205220b6cbb7b673e124709898a1f994';
const sourcePath = process.argv[2];
if (!sourcePath) throw Error('Usage: node generate-history-agent-catalog-oracle-v53.mjs <exact-pre-V53-HistoryPanel.tsx> [output]');
const source = fs.readFileSync(sourcePath, 'utf8');
const sha = value => createHash('sha256').update(value).digest('hex');
if (sha(source) !== expectedSourceSHA) throw Error('V53_ORACLE_REQUIRES_EXACT_PREIMAGE');
const bounds = {
  actions: ['const isRawAction = (', 'const historyActionToolUseId = ('],
  locals: ['const isLocalPromptEntry = (', 'const findServerPromptEntry = ('],
  agentKey: ['const historyAgentKey = (', 'interface HistoryAgentInspectorController'],
  callIdentity: ['const historySubagentCallIdentity = (', '// One parsed step of a subagent'],
  collectors: ['const collectHistoryBackgroundChips = (', '// Entry uuids that currently have a LIVE background chip.'],
  rewind: ['const entryClockMs = (', 'const serverHistoryMaterializedRewindBranch = ('],
};
const fragments = {};
for (const [name, [start, end]] of Object.entries(bounds)) {
  const from = source.indexOf(start), to = source.indexOf(end, from + start.length);
  if (from < 0 || to <= from || source.indexOf(start, from + start.length) >= 0)
    throw Error('V53_ORACLE_NONUNIQUE_SOURCE_' + name);
  const text = source.slice(from, to);
  if (Buffer.byteLength(text) > 20 * 1024) throw Error('V53_ORACLE_FRAGMENT_TOO_LARGE');
  fragments[name] = text;
}
const pins = {
  kind: 'literal-pre-V53-collector-oracle',
  source: 'src/renderer/components/Workspace/HistoryPanel.tsx',
  sourceBytes: Buffer.byteLength(source), sourceSHA256: sha(source),
  fragments: Object.fromEntries(Object.entries(fragments).map(([name, text]) => [name,
    { bytes: Buffer.byteLength(text), sha256: sha(text) }])),
};
const code = stripTypeScriptTypes(Object.values(fragments).join('\n'), { mode: 'strip' });
const output = '// GENERATED by scripts/generate-history-agent-catalog-oracle-v53.mjs.\n'
  + '// Literal old collectors: native Map/arrays are confined to this TEST oracle.\n'
  + '// This is neither the new implementation nor a production fallback.\n'
  + "'use strict';\n"
  + 'const sourcePins = Object.freeze(' + JSON.stringify(pins, null, 2) + ');\n'
  + 'function createHistoryAgentCatalogOracle({ isHistoryTaskChipLive, isHistoryBackgroundTaskLive, projectNativeRewindPreview }) {\n'
  + "const LOCAL_PROMPT_PREFIX = 'local-prompt-';\nconst LOCAL_REWIND_PREFIX = 'local-rewind-';\nconst LOCAL_COMPACT_ERROR_PREFIX = 'local-compact-error-';\n"
  + code
  + '\nreturn Object.freeze({ collectHistoryBackgroundChips, collectHistoryAgentChips, historyAgentKey, historySubagentCallIdentity, isRawAction, isTaskAction, isLocalPromptEntry, buildRewindPreviewEntries });\n}\n'
  + 'module.exports = { sourcePins, createHistoryAgentCatalogOracle };\n';
const outputPath = process.argv[3] || path.join(path.dirname(fileURLToPath(import.meta.url)), 'test-support/history-agent-catalog-oracle.cjs');
fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, output);
console.log(JSON.stringify({ ...pins, outputBytes: Buffer.byteLength(output), outputSHA256: sha(output),
  node: process.version, compileScope: 'bounded literal fragments only' }));
