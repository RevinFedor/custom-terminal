test('failed compile, missing marker, wrong architecture/ABI and source race leave old output intact', async t => {
  for (const scenario of ['compiler failure', 'marker', 'arch', 'ABI', 'header ABI', 'source race']) {
    await t.test(scenario, async t => {
      const f = await fixture(t);
      const release = path.join(f.pty, 'build/Release');
      await fs.mkdir(release, { recursive: true });
      const file = path.join(release, 'pty.node');
      await fs.writeFile(file, 'old');
      const inode = (await fs.stat(file)).ino;
      const compiler = scenario === 'compiler failure' ? async () => { throw new Error('compiler failed'); }
        : fakeCompiler(f, { marker: scenario !== 'marker', arch: scenario === 'arch' ? 'x64' : 'arm64',
          meta: scenario === 'ABI' ? 'arm64--999' : 'arm64--119',
          headerABI: scenario === 'header ABI' ? 999 : 119,
          onBuild: scenario === 'source race' ? () => fs.appendFile(path.join(f.pty, 'src/unix/pty.cc'), '\n') : undefined });
      await assert.rejects(rebuildNodePty(f.target, { scratchParent: f.root, rebuild: compiler }), /compiler failed|marker|architecture|ABI mismatch|pinned originals/);
      assert.equal(await fs.readFile(file, 'utf8'), 'old');
      assert.equal((await fs.stat(file)).ino, inode);
      assert.deepEqual(await fs.readdir(f.root), ['project']);
    });
  }
});

test('publication refuses symlink targets and build directory escapes', async t => {
  const f = await fixture(t);
  const external = path.join(f.root, 'external');
  await fs.mkdir(external);
  const victim = path.join(external, 'victim');
  await fs.writeFile(victim, 'preserve');
  const link = path.join(f.root, 'link');
  await fs.symlink(victim, link);
  await assert.rejects(atomicPublish(link, Buffer.from('overwrite')), /not a regular file/);
  await fs.symlink(external, path.join(f.pty, 'build'));
  await assert.rejects(rebuildNodePty(f.target, { scratchParent: f.root, rebuild: fakeCompiler(f) }), /not a real directory/);
  assert.equal(await fs.readFile(victim, 'utf8'), 'preserve');
  assert.deepEqual(await fs.readdir(external), ['victim']);
});

test('actual local builder skip reader accepts published metadata, before any prebuild selection', async t => {
  const f = await fixture(t);
  const proof = await rebuildNodePty(f.target, { scratchParent: f.root, rebuild: fakeCompiler(f) });
  const require = createRequire(path.join(projectDir, 'node_modules/app-builder-lib/package.json'));
  const nestedDir = path.dirname(require.resolve('@electron/rebuild'));
  const { ModuleRebuilder } = require(path.join(nestedDir, 'module-rebuilder.js'));
  // Only the read-only metadata predicate is invoked, never rebuildModuleAt.
  const skip = await ModuleRebuilder.prototype.alreadyBuiltByRebuild.call({
    metaPath: path.join(f.pty, 'build/Release/.forge-meta'), metaData: 'arm64--119',
  });
  assert.equal(skip, true);
  await verifyPublished(f.project, proof);
  const rebuildSource = await fs.readFile(path.join(nestedDir, 'rebuild.js'), 'utf8');
  assert.ok(rebuildSource.indexOf('!this.force && await moduleRebuilder.alreadyBuiltByRebuild()') < rebuildSource.indexOf('await moduleRebuilder.rebuild(cacheKey)'));
  const platform = await fs.readFile(path.join(projectDir, 'node_modules/app-builder-lib/out/platformPackager.js'), 'utf8');
  const positions = ['await beforePack(', 'await this.info.installAppDependencies(', 'await afterExtract(', 'this.copyAppFiles('].map(s => platform.indexOf(s));
  assert.ok(positions.every((p, i) => p >= 0 && (i === 0 || p > positions[i - 1])));
  await checkToolchain(projectDir); // read-only, includes the nested rebuilder
  const pkg = JSON.parse(await fs.readFile(path.join(projectDir, 'package.json')));
  assert.equal(pkg.build.beforePack, './scripts/node-pty-build.mjs');
  assert.equal(pkg.build.afterExtract, pkg.build.beforePack);
  assert.notEqual(pkg.build.npmRebuild, false);
  assert.match(pkg.scripts._rebuild, /node scripts\/node-pty-build.mjs/);
  assert.ok(pkg.scripts.build.indexOf('validate-app-asar.mjs') < pkg.scripts.build.indexOf('npm run sign:local-fast'));
});

