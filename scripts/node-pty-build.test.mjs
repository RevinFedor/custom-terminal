const projectDir = fileURLToPath(new URL('../', import.meta.url));
const sourcePty = path.join(projectDir, 'node_modules/node-pty');
const sources = ['package.json', 'binding.gyp', 'src/unix/pty.cc', 'src/unix/spawn-helper.cc', 'lib/utils.js', 'node_modules/node-addon-api'];

// These tests never compile, dlopen, execute a native file, start Electron/PTY,
// or write to the real node_modules.
async function fixture(t) {
  const root = await fs.mkdtemp(path.join(tmpdir(), 'noted-pty-test-'));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const project = path.join(root, 'project');
  const pty = path.join(project, 'node_modules/node-pty');
  await fs.mkdir(pty, { recursive: true });
  await fs.writeFile(path.join(project, 'package.json'), '{"name":"noted-terminal","version":"1.0.0"}');
  for (const name of sources) {
    await fs.mkdir(path.dirname(path.join(pty, name)), { recursive: true });
    await fs.cp(path.join(sourcePty, name), path.join(pty, name), { recursive: true });
  }
  return { root, project, pty, target: { projectDir: project, platform: 'darwin', arch: 'arm64', electronVersion: ELECTRON_VERSION } };
}

function fakeCompiler({ root, pty }, { marker = true, arch = 'arm64', meta = 'arm64--' + ELECTRON_ABI, headerABI = 119, onBuild } = {}) {
  return async options => {
    assert.equal(path.dirname(options.buildPath), root);
    assert.deepEqual(options, {
      buildPath: options.buildPath, projectRootPath: options.buildPath,
      electronVersion: ELECTRON_VERSION, arch: 'arm64', platform: 'darwin',
      onlyModules: ['node-pty'], force: true, buildFromSource: true,
      mode: 'sequential', useCache: false, disablePreGypCopy: true,
    });
    const module = path.join(options.buildPath, 'node_modules/node-pty');
    assert.notEqual(module, pty);
    assert.equal((await fs.lstat(module)).isSymbolicLink(), false);
    await assert.rejects(fs.stat(path.join(module, 'build')), { code: 'ENOENT' });
    await assert.rejects(fs.stat(path.join(module, 'prebuilds')), { code: 'ENOENT' });
    const cc = await fs.readFile(path.join(module, 'src/unix/pty.cc'), 'utf8');
    assert.ok(cc.includes('std::unique_ptr<ExitEvent> exit_event(raw)'));
    assert.ok(cc.endsWith(MARKER_SOURCE));
    assert.equal(JSON.parse(await fs.readFile(path.join(module, 'node_modules/node-addon-api/package.json'))).version, '7.1.1');
    const release = path.join(module, 'build/Release');
    await fs.mkdir(release, { recursive: true });
    await fs.writeFile(path.join(module, 'build/config.gypi'), '# Generated by node-gyp\n' + JSON.stringify({ variables: { node_module_version: headerABI, target_arch: 'arm64' } }));
    await fs.writeFile(path.join(release, 'pty.node'), macho({ marker, arch }));
    await fs.writeFile(path.join(release, 'spawn-helper'), macho({ marker: false, type: 2, arch }));
    await fs.writeFile(path.join(release, '.forge-meta'), meta);
    if (onBuild) await onBuild();
  };
}

test('exact ordinary candidate patch is idempotent; drift is refused', async () => {
  const [gyp, pty] = await Promise.all(['binding.gyp', 'src/unix/pty.cc'].map(f => fs.readFile(path.join(sourcePty, f), 'utf8')));
  const patched = patchSources(gyp, pty);
  assert.equal(sha256(patched.gyp), '911f13eb706ef6af9ac8f78c1e3558f17ce90e705d0ee17eb3a4d0e19f28da25');
  assert.equal(sha256(patched.pty.slice(0, -MARKER_SOURCE.length)), '8e1a7918403a6995655affc6b374e4e7604e60b1c52e3eacfa1876f41200323b');
  assert.deepEqual(patchSources(patched.gyp, patched.pty), patched);
  assert.throws(() => patchSources(gyp + '\n', pty), /binding.gyp SHA drift/);
  assert.throws(() => patchSources(gyp, patched.pty.replace('unique_ptr', 'shared_ptr')), /pty.cc SHA drift/);
});

test('private rebuild publishes outputs atomically; old open inode and source bytes survive', async t => {
  const f = await fixture(t);
  const release = path.join(f.pty, 'build/Release');
  await fs.mkdir(release, { recursive: true });
  const file = path.join(release, 'pty.node');
  await fs.writeFile(file, 'old mapped bytes');
  const old = await fs.open(file, 'r');
  t.after(() => old.close());
  const inode = (await old.stat()).ino;
  const proof = await rebuildNodePty(f.target, { scratchParent: f.root, rebuild: fakeCompiler(f) });
  assert.notEqual((await fs.stat(file)).ino, inode);
  assert.equal(await old.readFile('utf8'), 'old mapped bytes');
  assert.equal(await fs.readFile(path.join(release, '.forge-meta'), 'utf8'), 'arm64--119');
  assert.equal((await fs.stat(path.join(release, 'spawn-helper'))).mode & 0o777, 0o755);
  assert.deepEqual(await fs.readFile(path.join(f.pty, 'src/unix/pty.cc')), await fs.readFile(path.join(sourcePty, 'src/unix/pty.cc')));
  assert.deepEqual(await fs.readFile(path.join(f.pty, 'binding.gyp')), await fs.readFile(path.join(sourcePty, 'binding.gyp')));
  await verifyPublished(f.project, proof);
  const nextInode = (await fs.stat(file)).ino;
  const again = await rebuildNodePty(f.target, { scratchParent: f.root, rebuild: fakeCompiler(f) });
  assert.deepEqual(again, proof);
  assert.equal((await fs.stat(file)).ino, nextInode, 'identical output is an idempotent no-op');
  assert.deepEqual(await fs.readdir(f.root), ['project'], 'scratch is cleaned, only own subtree');
  await fs.writeFile(file, macho({ marker: false }));
  await assert.rejects(verifyPublished(f.project, proof), /compiled node-pty fix marker/);
});

test('binary marker alone cannot mask replacement between beforePack and afterExtract', async t => {
  const f = await fixture(t);
  const proof = await rebuildNodePty(f.target, { scratchParent: f.root, rebuild: fakeCompiler(f) });
  const changed = macho();
  changed[500] = 1;
  await fs.writeFile(path.join(f.pty, 'build/Release/pty.node'), changed);
  await assert.rejects(verifyPublished(f.project, proof), /replaced the prepared/);
});

