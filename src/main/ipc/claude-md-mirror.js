// CLAUDE.md mirror — синхронизирует CLAUDE.md в корне проекта в AGENTS.md и GEMINI.md.
//
// 1) fs.watch на projectRoot. Когда CLAUDE.md меняется (или появляется/исчезает)
//    debounce'им и переписываем mirror'ы с маркером BANNER в начале.
// 2) Тот же watcher ловит правки самих mirror'ов — если содержимое разошлось с
//    CLAUDE.md, перезатираем mirror обратно (источник истины — CLAUDE.md).
// 3) Internal-write guard: чтобы наши собственные writes не порождали бесконечный
//    цикл, держим Set путей, которые ждём «своё» fs-событие и игнорируем его.
// 4) Тогл (per-app) живёт в SQLite через app:setState ключ 'claudeMdMirrorEnabled',
//    управляется из renderer'а. Watcher запущен всегда (чтобы статус-инфо была
//    свежей), но записи в mirror'ы делаются только когда enabled=true.

const { ipcMain } = require('electron');
const fs = require('fs');
const path = require('path');

const SOURCE_NAME = 'CLAUDE.md';
const MIRROR_NAMES = ['AGENTS.md', 'GEMINI.md'];
const BANNER = '<!-- AUTOGENERATED MIRROR of CLAUDE.md. Source of truth is CLAUDE.md — edits to this file will be overwritten. -->';
const DEBOUNCE_MS = 300;
// Internal-write guard: how long after we write a file we ignore subsequent
// fs.watch events on it. fs.watch on macOS can fire multiple times for one write
// (open, write, close — all distinct events). 1500ms is conservative.
const INTERNAL_WRITE_TTL_MS = 1500;

// projectId → state
//   projectPath, watcher, debounceTimer, ignoreUntil: Map<absPath, expiresAt>
//   lastSourceMtime: number | null, lastMirrorWriteAt: Map<absPath, number>
const watchedProjects = new Map();

// In-memory mirror of enabled flag. Renderer pushes via set-enabled IPC.
// Hydrated from SQLite on app boot via setEnabledFromStorage().
let mirrorEnabled = false;

function getMirrorPaths(projectPath) {
  return MIRROR_NAMES.map((name) => path.join(projectPath, name));
}

function readSourceContent(projectPath) {
  const src = path.join(projectPath, SOURCE_NAME);
  if (!fs.existsSync(src)) return null;
  try {
    return fs.readFileSync(src, 'utf8');
  } catch (err) {
    console.error('[ClaudeMdMirror] read source failed:', err.message);
    return null;
  }
}

function statSafe(p) {
  try { return fs.statSync(p); } catch { return null; }
}

function buildMirrorContent(sourceContent) {
  // Single leading line + blank line so subsequent markdown still renders cleanly.
  // BANNER is an HTML comment — invisible in rendered markdown (GitHub, etc).
  return `${BANNER}\n\n${sourceContent}`;
}

function stripBanner(content) {
  // Used to compare mirror-on-disk with what we WOULD write — banner is ours,
  // we don't want a "different" verdict just because someone deleted the line.
  if (content.startsWith(BANNER + '\n\n')) return content.slice(BANNER.length + 2);
  if (content.startsWith(BANNER + '\n')) return content.slice(BANNER.length + 1);
  if (content.startsWith(BANNER)) return content.slice(BANNER.length);
  return content;
}

function markInternalWrite(state, absPath) {
  state.ignoreUntil.set(absPath, Date.now() + INTERNAL_WRITE_TTL_MS);
}

function isInternalWrite(state, absPath) {
  const exp = state.ignoreUntil.get(absPath);
  if (!exp) return false;
  if (exp < Date.now()) {
    state.ignoreUntil.delete(absPath);
    return false;
  }
  return true;
}

function writeMirrorIfNeeded(state, mirrorPath, expected) {
  let existing = null;
  try { existing = fs.readFileSync(mirrorPath, 'utf8'); } catch { /* missing */ }
  if (existing === expected) return false; // already in sync, no write
  markInternalWrite(state, mirrorPath);
  fs.writeFileSync(mirrorPath, expected, 'utf8');
  state.lastMirrorWriteAt.set(mirrorPath, Date.now());
  return true;
}

function syncMirrors(state) {
  if (!mirrorEnabled) return;
  const src = readSourceContent(state.projectPath);
  if (src === null) return; // source missing — never touch mirrors
  const expected = buildMirrorContent(src);
  for (const mirrorPath of getMirrorPaths(state.projectPath)) {
    try {
      writeMirrorIfNeeded(state, mirrorPath, expected);
    } catch (err) {
      console.error('[ClaudeMdMirror] write failed:', mirrorPath, err.message);
    }
  }
}

function computeStatus(state) {
  const src = path.join(state.projectPath, SOURCE_NAME);
  const srcStat = statSafe(src);
  const srcContent = srcStat ? readSourceContent(state.projectPath) : null;
  const expected = srcContent !== null ? buildMirrorContent(srcContent) : null;

  const mirrors = getMirrorPaths(state.projectPath).map((mirrorPath) => {
    const st = statSafe(mirrorPath);
    let inSync = false;
    if (st && expected !== null) {
      try {
        const onDisk = fs.readFileSync(mirrorPath, 'utf8');
        inSync = onDisk === expected;
      } catch { inSync = false; }
    }
    return {
      path: mirrorPath,
      name: path.basename(mirrorPath),
      exists: !!st,
      sizeBytes: st ? st.size : 0,
      mtime: st ? st.mtimeMs : null,
      inSync,
      lastWriteAt: state.lastMirrorWriteAt.get(mirrorPath) || null,
    };
  });

  return {
    enabled: mirrorEnabled,
    source: {
      path: src,
      name: SOURCE_NAME,
      exists: !!srcStat,
      sizeBytes: srcStat ? srcStat.size : 0,
      mtime: srcStat ? srcStat.mtimeMs : null,
    },
    mirrors,
  };
}

function pushStatus(mainWindow, projectId, status) {
  if (!mainWindow || mainWindow.isDestroyed()) return;
  mainWindow.webContents.send('mirror:status', { projectId, ...status });
}

function scheduleSync(state, mainWindow, projectId) {
  if (state.debounceTimer) clearTimeout(state.debounceTimer);
  state.debounceTimer = setTimeout(() => {
    state.debounceTimer = null;
    syncMirrors(state);
    pushStatus(mainWindow, projectId, computeStatus(state));
  }, DEBOUNCE_MS);
}

function startWatching(projectId, projectPath, mainWindow) {
  if (watchedProjects.has(projectId)) return;

  const state = {
    projectPath,
    watcher: null,
    debounceTimer: null,
    ignoreUntil: new Map(),
    lastMirrorWriteAt: new Map(),
  };
  watchedProjects.set(projectId, state);

  try {
    state.watcher = fs.watch(projectPath, { persistent: true }, (_evt, filename) => {
      if (!filename) return;
      // Only react to source + mirror files. Ignore everything else in the root.
      if (filename !== SOURCE_NAME && !MIRROR_NAMES.includes(filename)) return;
      const abs = path.join(projectPath, filename);
      if (isInternalWrite(state, abs)) return;
      scheduleSync(state, mainWindow, projectId);
    });
  } catch (err) {
    console.error('[ClaudeMdMirror] watch failed:', projectPath, err.message);
  }

  // On first watch — sync once and push initial status (renderer doesn't show stale).
  syncMirrors(state);
  pushStatus(mainWindow, projectId, computeStatus(state));
}

function stopWatching(projectId) {
  const state = watchedProjects.get(projectId);
  if (!state) return;
  if (state.debounceTimer) clearTimeout(state.debounceTimer);
  if (state.watcher) {
    try { state.watcher.close(); } catch {}
  }
  watchedProjects.delete(projectId);
}

function reSyncAll(mainWindow) {
  // After toggle ON or after explicit "create now": walk every active watcher
  // and force a sync + status push. Used so the UI updates without waiting for
  // the next fs event (which won't fire if the source is already in sync).
  for (const [projectId, state] of watchedProjects.entries()) {
    syncMirrors(state);
    pushStatus(mainWindow, projectId, computeStatus(state));
  }
}

function register({ getMainWindow, projectManager }) {
  const mw = () => getMainWindow();

  // Hydrate flag from SQLite once on registration. projectManager.db.getState
  // mirrors what app:getState does, so the flag is honoured even before any
  // renderer has connected (e.g. during very early project open).
  try {
    if (projectManager && projectManager.db && typeof projectManager.db.getAppState === 'function') {
      const v = projectManager.db.getAppState('claudeMdMirrorEnabled');
      mirrorEnabled = v === '1' || v === 'true' || v === true;
    }
  } catch (err) {
    console.error('[ClaudeMdMirror] hydrate enabled failed:', err.message);
  }

  ipcMain.handle('mirror:watch', (event, { projectId, projectPath }) => {
    try {
      if (!projectId || !projectPath) return { success: false, error: 'projectId+projectPath required' };
      startWatching(projectId, projectPath, mw());
      return { success: true };
    } catch (err) {
      return { success: false, error: err.message };
    }
  });

  ipcMain.handle('mirror:unwatch', (event, { projectId }) => {
    stopWatching(projectId);
    return { success: true };
  });

  ipcMain.handle('mirror:get-status', (event, { projectId }) => {
    const state = watchedProjects.get(projectId);
    if (!state) return { success: false, error: 'Not watching' };
    return { success: true, status: computeStatus(state) };
  });

  ipcMain.handle('mirror:set-enabled', (event, { enabled }) => {
    const next = !!enabled;
    if (next === mirrorEnabled) return { success: true, enabled: mirrorEnabled };
    mirrorEnabled = next;
    // Persist via projectManager (single source — same place renderer's
    // app:setState handler writes to).
    try {
      if (projectManager && projectManager.db && typeof projectManager.db.setAppState === 'function') {
        projectManager.db.setAppState('claudeMdMirrorEnabled', next ? '1' : '0');
      }
    } catch (err) {
      console.error('[ClaudeMdMirror] persist enabled failed:', err.message);
    }
    // ON: force a re-sync across all watched projects so users see mirrors
    // appear/refresh immediately. OFF: just push updated status (so the UI
    // toggle reflects the new state).
    reSyncAll(mw());
    return { success: true, enabled: mirrorEnabled };
  });

  ipcMain.handle('mirror:create-now', (event, { projectId }) => {
    const state = watchedProjects.get(projectId);
    if (!state) return { success: false, error: 'Not watching' };
    if (!mirrorEnabled) return { success: false, error: 'Mirror disabled' };
    syncMirrors(state);
    pushStatus(mw(), projectId, computeStatus(state));
    return { success: true };
  });

  const cleanupAll = () => {
    for (const projectId of Array.from(watchedProjects.keys())) stopWatching(projectId);
  };
  process.on('exit', cleanupAll);
}

module.exports = { register };
