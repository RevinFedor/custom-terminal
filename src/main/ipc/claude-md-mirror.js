// CLAUDE.md mirror — синхронизирует CLAUDE.md в корне проекта в AGENTS.md и GEMINI.md.
//
// 1) fs.watch на projectRoot. Когда CLAUDE.md меняется (или появляется/исчезает)
//    debounce'им и переписываем mirror'ы с маркером BANNER в начале.
// 2) Тот же watcher ловит правки самих mirror'ов — если содержимое разошлось с
//    CLAUDE.md, перезатираем mirror обратно (источник истины — CLAUDE.md).
// 3) Internal-write guard: чтобы наши собственные writes не порождали бесконечный
//    цикл, держим Set путей, которые ждём «своё» fs-событие и игнорируем его.
// 4) Тогл (per-app) живёт в SQLite через app:setState ключ 'claudeMdMirrorEnabled',
//    управляется из renderer'а. Watcher запущен всегда (чтобы статус-инфо была
//    свежей), но записи в mirror'ы делаются только когда enabled=true.

const { ipcMain } = require('electron');
const fs = require('fs');
const os = require('os');
const path = require('path');

const SOURCE_NAME = 'CLAUDE.md';
const MIRROR_NAMES = ['AGENTS.md', 'GEMINI.md'];
const BANNER = '<!-- AUTOGENERATED MIRROR of CLAUDE.md. Source of truth is CLAUDE.md — edits to this file will be overwritten. -->';
const DEBOUNCE_MS = 300;
const SKILLS_SYNC_DEBOUNCE_MS = 300;
// Internal-write guard: how long after we write a file we ignore subsequent
// fs.watch events on it. fs.watch on macOS can fire multiple times for one write
// (open, write, close — all distinct events). 1500ms is conservative.
const INTERNAL_WRITE_TTL_MS = 1500;
const SKILLS_INTERNAL_WRITE_TTL_MS = 1500;

// projectId → state
//   projectPath, watcher, debounceTimer, ignoreUntil: Map<absPath, expiresAt>
//   lastSourceMtime: number | null, lastMirrorWriteAt: Map<absPath, number>
const watchedProjects = new Map();

// In-memory mirror of enabled flag. Renderer pushes via set-enabled IPC.
// Hydrated from SQLite on app boot via setEnabledFromStorage().
let mirrorEnabled = false;

const skillsWatchState = {
  watchers: [],
  debounceTimer: null,
  syncing: false,
  pendingReason: null,
  ignoreTargetUntil: 0,
  lastAutoSyncAt: null,
  lastAutoSyncError: null,
  watchErrors: [],
  watchedKey: '',
  mainWindow: null,
};

function getMirrorPaths(projectPath) {
  return MIRROR_NAMES.map((name) => path.join(projectPath, name));
}

function readSourceContent(projectPath) {
  const src = path.join(projectPath, SOURCE_NAME);
  if (!fs.existsSync(src)) return null;
  try {
    return fs.readFileSync(src, 'utf8');
  } catch (err) {
    console.error('[ClaudeMdMirror] read source failed:', err.message);
    return null;
  }
}

function statSafe(p) {
  try { return fs.statSync(p); } catch { return null; }
}

function buildMirrorContent(sourceContent) {
  // Single leading line + blank line so subsequent markdown still renders cleanly.
  // BANNER is an HTML comment — invisible in rendered markdown (GitHub, etc).
  return `${BANNER}\n\n${sourceContent}`;
}

function stripBanner(content) {
  // Used to compare mirror-on-disk with what we WOULD write — banner is ours,
  // we don't want a "different" verdict just because someone deleted the line.
  if (content.startsWith(BANNER + '\n\n')) return content.slice(BANNER.length + 2);
  if (content.startsWith(BANNER + '\n')) return content.slice(BANNER.length + 1);
  if (content.startsWith(BANNER)) return content.slice(BANNER.length);
  return content;
}

function markInternalWrite(state, absPath) {
  state.ignoreUntil.set(absPath, Date.now() + INTERNAL_WRITE_TTL_MS);
}

function isInternalWrite(state, absPath) {
  const exp = state.ignoreUntil.get(absPath);
  if (!exp) return false;
  if (exp < Date.now()) {
    state.ignoreUntil.delete(absPath);
    return false;
  }
  return true;
}

function writeMirrorIfNeeded(state, mirrorPath, expected) {
  let existing = null;
  try { existing = fs.readFileSync(mirrorPath, 'utf8'); } catch { /* missing */ }
  if (existing === expected) return false; // already in sync, no write
  markInternalWrite(state, mirrorPath);
  fs.writeFileSync(mirrorPath, expected, 'utf8');
  state.lastMirrorWriteAt.set(mirrorPath, Date.now());
  return true;
}

function syncMirrors(state) {
  if (!mirrorEnabled) return;
  const src = readSourceContent(state.projectPath);
  if (src === null) return; // source missing — never touch mirrors
  const expected = buildMirrorContent(src);
  for (const mirrorPath of getMirrorPaths(state.projectPath)) {
    try {
      writeMirrorIfNeeded(state, mirrorPath, expected);
    } catch (err) {
      console.error('[ClaudeMdMirror] write failed:', mirrorPath, err.message);
    }
  }
}

function computeStatus(state) {
  const src = path.join(state.projectPath, SOURCE_NAME);
  const srcStat = statSafe(src);
  const srcContent = srcStat ? readSourceContent(state.projectPath) : null;
  const expected = srcContent !== null ? buildMirrorContent(srcContent) : null;

  const mirrors = getMirrorPaths(state.projectPath).map((mirrorPath) => {
    const st = statSafe(mirrorPath);
    let inSync = false;
    if (st && expected !== null) {
      try {
        const onDisk = fs.readFileSync(mirrorPath, 'utf8');
        inSync = onDisk === expected;
      } catch { inSync = false; }
    }
    return {
      path: mirrorPath,
      name: path.basename(mirrorPath),
      exists: !!st,
      sizeBytes: st ? st.size : 0,
      mtime: st ? st.mtimeMs : null,
      inSync,
      lastWriteAt: state.lastMirrorWriteAt.get(mirrorPath) || null,
    };
  });

  return {
    enabled: mirrorEnabled,
    source: {
      path: src,
      name: SOURCE_NAME,
      exists: !!srcStat,
      sizeBytes: srcStat ? srcStat.size : 0,
      mtime: srcStat ? srcStat.mtimeMs : null,
    },
    mirrors,
  };
}

function pushStatus(mainWindow, projectId, status) {
  if (!mainWindow || mainWindow.isDestroyed()) return;
  mainWindow.webContents.send('mirror:status', { projectId, ...status });
}

function scheduleSync(state, mainWindow, projectId) {
  if (state.debounceTimer) clearTimeout(state.debounceTimer);
  state.debounceTimer = setTimeout(() => {
    state.debounceTimer = null;
    syncMirrors(state);
    pushStatus(mainWindow, projectId, computeStatus(state));
  }, DEBOUNCE_MS);
}

function startWatching(projectId, projectPath, mainWindow) {
  if (watchedProjects.has(projectId)) return;

  const state = {
    projectPath,
    watcher: null,
    debounceTimer: null,
    ignoreUntil: new Map(),
    lastMirrorWriteAt: new Map(),
  };
  watchedProjects.set(projectId, state);

  try {
    state.watcher = fs.watch(projectPath, { persistent: true }, (_evt, filename) => {
      if (!filename) return;
      // Only react to source + mirror files. Ignore everything else in the root.
      if (filename !== SOURCE_NAME && !MIRROR_NAMES.includes(filename)) return;
      const abs = path.join(projectPath, filename);
      if (isInternalWrite(state, abs)) return;
      scheduleSync(state, mainWindow, projectId);
    });
  } catch (err) {
    console.error('[ClaudeMdMirror] watch failed:', projectPath, err.message);
  }

  // On first watch — sync once and push initial status (renderer doesn't show stale).
  syncMirrors(state);
  pushStatus(mainWindow, projectId, computeStatus(state));
}

function stopWatching(projectId) {
  const state = watchedProjects.get(projectId);
  if (!state) return;
  if (state.debounceTimer) clearTimeout(state.debounceTimer);
  if (state.watcher) {
    try { state.watcher.close(); } catch {}
  }
  watchedProjects.delete(projectId);
}

function reSyncAll(mainWindow) {
  // After toggle ON or after explicit "create now": walk every active watcher
  // and force a sync + status push. Used so the UI updates without waiting for
  // the next fs event (which won't fire if the source is already in sync).
  for (const [projectId, state] of watchedProjects.entries()) {
    syncMirrors(state);
    pushStatus(mainWindow, projectId, computeStatus(state));
  }
}

function resolveSkillsDirs() {
  const home = os.homedir();
  const claudeHome = process.env.CLAUDE_HOME || path.join(home, '.claude');
  const codexHome = process.env.CODEX_HOME || path.join(home, '.codex');
  return {
    sourceDir: path.join(claudeHome, 'skills'),
    targetDir: path.join(codexHome, 'skills'),
  };
}

function listTopLevelSkillDirs(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true })
    .filter((entry) => !entry.name.startsWith('.') && (entry.isDirectory() || entry.isSymbolicLink()))
    .map((entry) => entry.name)
    .sort((a, b) => a.localeCompare(b));
}

function unwrapInlineYamlScalar(raw) {
  const value = String(raw || '').trim();
  if (value.length >= 2 && value.startsWith('"') && value.endsWith('"')) {
    try {
      return JSON.parse(value);
    } catch {
      return value.slice(1, -1);
    }
  }
  if (value.length >= 2 && value.startsWith("'") && value.endsWith("'")) {
    return value.slice(1, -1).replace(/''/g, "'");
  }
  return value;
}

function toYamlDoubleQuoted(value) {
  return `"${String(value)
    .replace(/\\/g, '\\\\')
    .replace(/"/g, '\\"')
    .replace(/\r/g, '\\r')
    .replace(/\n/g, '\\n')
    .replace(/\t/g, '\\t')}"`;
}

function normalizeCodexSkillFrontmatter(skillDir) {
  const skillPath = path.join(skillDir, 'SKILL.md');
  if (!fs.existsSync(skillPath)) return false;

  const content = fs.readFileSync(skillPath, 'utf8');
  const newline = content.includes('\r\n') ? '\r\n' : '\n';
  const lines = content.split(/\r?\n/);
  if (lines[0] !== '---') return false;

  const endIdx = lines.indexOf('---', 1);
  if (endIdx === -1) return false;

  let changed = false;
  for (let i = 1; i < endIdx; i++) {
    const match = lines[i].match(/^(name|description):\s*(.*)$/);
    if (!match) continue;

    const [, key, rawValue] = match;
    if (rawValue.trim().startsWith('|') || rawValue.trim().startsWith('>')) continue;

    const next = `${key}: ${toYamlDoubleQuoted(unwrapInlineYamlScalar(rawValue))}`;
    if (next !== lines[i]) {
      lines[i] = next;
      changed = true;
    }
  }

  if (!changed) return false;
  fs.writeFileSync(skillPath, lines.join(newline), 'utf8');
  return true;
}

function computeSkillsSyncStatus() {
  const { sourceDir, targetDir } = resolveSkillsDirs();
  const sourceExists = fs.existsSync(sourceDir);
  const targetExists = fs.existsSync(targetDir);
  const claudeSkills = listTopLevelSkillDirs(sourceDir);
  const codexSkills = listTopLevelSkillDirs(targetDir);
  const claudeSet = new Set(claudeSkills);
  const codexSet = new Set(codexSkills);
  return {
    success: true,
    sourceDir,
    targetDir,
    sourceExists,
    targetExists,
    claudeSkills,
    codexSkills,
    missingInCodex: claudeSkills.filter((name) => !codexSet.has(name)),
    codexOnly: codexSkills.filter((name) => !claudeSet.has(name)),
    watcher: getSkillsWatchInfo(),
  };
}

function syncClaudeSkillsToCodex() {
  const { sourceDir, targetDir } = resolveSkillsDirs();
  if (!fs.existsSync(sourceDir)) {
    return { success: false, error: 'Claude skills directory not found', sourceDir, targetDir };
  }
  fs.mkdirSync(targetDir, { recursive: true });

  const copied = [];
  const normalized = [];
  const skipped = [];
  const errors = [];
  const entries = fs.readdirSync(sourceDir, { withFileTypes: true });
  for (const entry of entries) {
    if (entry.name.startsWith('.')) {
      skipped.push({ name: entry.name, reason: 'hidden/system' });
      continue;
    }
    if (!entry.isDirectory() && !entry.isSymbolicLink()) {
      skipped.push({ name: entry.name, reason: 'not directory' });
      continue;
    }
    const src = path.join(sourceDir, entry.name);
    const dst = path.join(targetDir, entry.name);
    try {
      fs.rmSync(dst, { recursive: true, force: true });
      fs.cpSync(src, dst, { recursive: true, force: true, preserveTimestamps: true });
      if (normalizeCodexSkillFrontmatter(dst)) normalized.push(entry.name);
      copied.push(entry.name);
    } catch (err) {
      errors.push({ name: entry.name, error: err.message });
    }
  }

  return {
    success: errors.length === 0,
    sourceDir,
    targetDir,
    copied,
    copiedCount: copied.length,
    normalized,
    skipped,
    errors,
    status: computeSkillsSyncStatus(),
  };
}

function getSkillsWatchInfo() {
  return {
    active: skillsWatchState.watchers.length > 0,
    watcherCount: skillsWatchState.watchers.length,
    lastAutoSyncAt: skillsWatchState.lastAutoSyncAt,
    lastAutoSyncError: skillsWatchState.lastAutoSyncError,
    errors: skillsWatchState.watchErrors.slice(-5),
  };
}

function recordSkillsWatchError(message) {
  skillsWatchState.watchErrors.push({ message, at: Date.now() });
  if (skillsWatchState.watchErrors.length > 20) skillsWatchState.watchErrors.splice(0, skillsWatchState.watchErrors.length - 20);
  console.warn('[SkillsSync] watcher:', message);
}

function closeSkillsWatchers() {
  if (skillsWatchState.debounceTimer) {
    clearTimeout(skillsWatchState.debounceTimer);
    skillsWatchState.debounceTimer = null;
  }
  for (const watcher of skillsWatchState.watchers) {
    try { watcher.close(); } catch {}
  }
  skillsWatchState.watchers = [];
  skillsWatchState.watchedKey = '';
}

function collectSkillWatchDirs(rootDir) {
  const dirs = [];
  const walk = (dir) => {
    dirs.push(dir);
    let entries = [];
    try {
      entries = fs.readdirSync(dir, { withFileTypes: true });
    } catch (err) {
      recordSkillsWatchError(`scan failed ${dir}: ${err.message}`);
      return;
    }
    for (const entry of entries) {
      if (entry.name.startsWith('.')) continue;
      if (!entry.isDirectory()) continue;
      walk(path.join(dir, entry.name));
    }
  };

  const st = statSafe(rootDir);
  if (st && st.isDirectory()) walk(rootDir);
  return dirs;
}

function createSkillsWatcher({ dir, kind, rootName = null, recursive = false }) {
  const watcher = fs.watch(dir, { persistent: true, recursive }, (_evt, filename) => {
    handleSkillsFsEvent(kind, filename, rootName);
  });
  watcher.on('error', (err) => recordSkillsWatchError(`${kind} watch failed ${dir}: ${err.message}`));
  skillsWatchState.watchers.push(watcher);
  return `${kind}:${recursive ? 'recursive' : 'flat'}:${dir}${rootName ? `:${rootName}` : ''}`;
}

function addSkillsWatchRoot(kind, rootDir) {
  const watched = [];
  const st = statSafe(rootDir);
  if (st && st.isDirectory()) {
    try {
      watched.push(createSkillsWatcher({ dir: rootDir, kind, recursive: true }));
      return watched;
    } catch (err) {
      recordSkillsWatchError(`${kind} recursive watch unavailable ${rootDir}: ${err.message}`);
    }

    for (const dir of collectSkillWatchDirs(rootDir)) {
      try {
        watched.push(createSkillsWatcher({ dir, kind }));
      } catch (err) {
        recordSkillsWatchError(`${kind} watch failed ${dir}: ${err.message}`);
      }
    }
    return watched;
  }

  const parentDir = path.dirname(rootDir);
  const parentStat = statSafe(parentDir);
  if (parentStat && parentStat.isDirectory()) {
    try {
      watched.push(createSkillsWatcher({ dir: parentDir, kind, rootName: path.basename(rootDir) }));
    } catch (err) {
      recordSkillsWatchError(`${kind} parent watch failed ${parentDir}: ${err.message}`);
    }
  }
  return watched;
}

function startSkillsWatchers(mainWindow) {
  skillsWatchState.mainWindow = mainWindow || skillsWatchState.mainWindow;
  closeSkillsWatchers();

  const { sourceDir, targetDir } = resolveSkillsDirs();
  const watched = [
    ...addSkillsWatchRoot('source', sourceDir),
    ...addSkillsWatchRoot('target', targetDir),
  ];
  skillsWatchState.watchedKey = watched.join('|');
  pushSkillsStatus(skillsWatchState.mainWindow, null, 'watch-started');
}

function handleSkillsFsEvent(kind, filename, rootName) {
  const rel = filename ? String(filename) : '';
  const first = rel.split(/[\\/]/).filter(Boolean)[0] || '';
  if (first.startsWith('.')) return;
  if (rootName && first && first !== rootName) return;
  if (kind === 'target' && (skillsWatchState.syncing || Date.now() < skillsWatchState.ignoreTargetUntil)) return;
  scheduleSkillsAutoSync(kind === 'source' ? 'source-change' : 'target-drift');
}

function scheduleSkillsAutoSync(reason) {
  if (skillsWatchState.debounceTimer) clearTimeout(skillsWatchState.debounceTimer);
  skillsWatchState.debounceTimer = setTimeout(() => {
    skillsWatchState.debounceTimer = null;
    if (skillsWatchState.syncing) {
      skillsWatchState.pendingReason = reason;
      return;
    }
    performSkillsSync(skillsWatchState.mainWindow, 'auto', reason);
  }, SKILLS_SYNC_DEBOUNCE_MS);
}

function performSkillsSync(mainWindow, mode = 'manual', reason = mode) {
  skillsWatchState.mainWindow = mainWindow || skillsWatchState.mainWindow;
  skillsWatchState.syncing = true;
  skillsWatchState.ignoreTargetUntil = Date.now() + SKILLS_INTERNAL_WRITE_TTL_MS;

  let result;
  try {
    result = syncClaudeSkillsToCodex();
    if (mode === 'manual' && result.success) {
      skillsWatchState.lastAutoSyncError = null;
    }
    if (mode === 'auto') {
      skillsWatchState.lastAutoSyncAt = Date.now();
      skillsWatchState.lastAutoSyncError = result.success
        ? null
        : (result.error || result.errors?.[0]?.error || 'unknown auto sync error');
    }
  } catch (err) {
    result = { success: false, error: err.message };
    if (mode === 'auto') {
      skillsWatchState.lastAutoSyncAt = Date.now();
      skillsWatchState.lastAutoSyncError = err.message;
    }
  } finally {
    skillsWatchState.ignoreTargetUntil = Date.now() + SKILLS_INTERNAL_WRITE_TTL_MS;
    skillsWatchState.syncing = false;
    startSkillsWatchers(skillsWatchState.mainWindow);
  }

  pushSkillsStatus(skillsWatchState.mainWindow, result, reason);
  if (skillsWatchState.pendingReason) {
    const pendingReason = skillsWatchState.pendingReason;
    skillsWatchState.pendingReason = null;
    scheduleSkillsAutoSync(pendingReason);
  }
  return result;
}

function pushSkillsStatus(mainWindow, result = null, reason = 'status') {
  if (!mainWindow || mainWindow.isDestroyed()) return;
  let status;
  try {
    status = computeSkillsSyncStatus();
  } catch (err) {
    status = { success: false, error: err.message, watcher: getSkillsWatchInfo() };
  }
  mainWindow.webContents.send('skills:sync-status', { reason, result, status });
}

function register({ getMainWindow, projectManager }) {
  const mw = () => getMainWindow();

  // Hydrate flag from SQLite once on registration. projectManager.db.getState
  // mirrors what app:getState does, so the flag is honoured even before any
  // renderer has connected (e.g. during very early project open).
  try {
    if (projectManager && projectManager.db && typeof projectManager.db.getAppState === 'function') {
      const v = projectManager.db.getAppState('claudeMdMirrorEnabled');
      mirrorEnabled = v === '1' || v === 'true' || v === true || v === 1;
    }
  } catch (err) {
    console.error('[ClaudeMdMirror] hydrate enabled failed:', err.message);
  }

  startSkillsWatchers(mw());

  ipcMain.handle('mirror:watch', (event, { projectId, projectPath }) => {
    try {
      if (!projectId || !projectPath) return { success: false, error: 'projectId+projectPath required' };
      startWatching(projectId, projectPath, mw());
      return { success: true };
    } catch (err) {
      return { success: false, error: err.message };
    }
  });

  ipcMain.handle('mirror:unwatch', (event, { projectId }) => {
    stopWatching(projectId);
    return { success: true };
  });

  ipcMain.handle('mirror:get-status', (event, { projectId }) => {
    const state = watchedProjects.get(projectId);
    if (!state) return { success: false, error: 'Not watching' };
    return { success: true, status: computeStatus(state) };
  });

  ipcMain.handle('mirror:set-enabled', (event, { enabled }) => {
    const next = !!enabled;
    if (next === mirrorEnabled) return { success: true, enabled: mirrorEnabled };
    mirrorEnabled = next;
    // Persist via projectManager (single source — same place renderer's
    // app:setState handler writes to).
    try {
      if (projectManager && projectManager.db && typeof projectManager.db.setAppState === 'function') {
        projectManager.db.setAppState('claudeMdMirrorEnabled', next);
      }
    } catch (err) {
      console.error('[ClaudeMdMirror] persist enabled failed:', err.message);
    }
    // ON: force a re-sync across all watched projects so users see mirrors
    // appear/refresh immediately. OFF: just push updated status (so the UI
    // toggle reflects the new state).
    reSyncAll(mw());
    return { success: true, enabled: mirrorEnabled };
  });

  ipcMain.handle('mirror:create-now', (event, { projectId }) => {
    const state = watchedProjects.get(projectId);
    if (!state) return { success: false, error: 'Not watching' };
    if (!mirrorEnabled) return { success: false, error: 'Mirror disabled' };
    syncMirrors(state);
    pushStatus(mw(), projectId, computeStatus(state));
    return { success: true };
  });

  ipcMain.handle('skills:sync-claude-to-codex', () => {
    try {
      return performSkillsSync(mw(), 'manual', 'manual');
    } catch (err) {
      return { success: false, error: err.message };
    }
  });

  ipcMain.handle('skills:get-sync-status', () => {
    try {
      return computeSkillsSyncStatus();
    } catch (err) {
      return { success: false, error: err.message };
    }
  });

  const cleanupAll = () => {
    for (const projectId of Array.from(watchedProjects.keys())) stopWatching(projectId);
    closeSkillsWatchers();
  };
  process.on('exit', cleanupAll);
}

module.exports = { register };
