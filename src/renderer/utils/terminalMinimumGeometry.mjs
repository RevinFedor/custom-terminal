// Своя минимальная геометрия терминала — «сколько строк и колонок нужно, чтобы
// им можно было пользоваться».
//
// Зачем вообще. Раскладку окон человек кроит как хочет: колонка может быть
// узкой, окно в колонке — низким, боковой терминал открывается в том, что
// осталось. Ограничивать сами окна ради терминала неправильно (юзер:
// *«ограничивать ширину окон я не хочу, это точно»*), но и молча подстраивать
// терминал под любой размер нельзя: у fit-адаптера свой пол — 2 колонки и 1
// строка, и TUI-агент в такой «сетке» просто перестаёт рисоваться.
//
// Поэтому правило перевёрнуто: НЕ окно диктует терминалу размер, а терминал
// имеет собственный минимум и, если места не дали, рисуется больше окна и
// обрезается его краем. Работоспособность важнее того, что нижние строки
// уехали под границу: обрезанный, но живой терминал чинится одним движением
// перегородки, а «сетка 2×1» не чинится ничем.
//
// Числа — в ЯЧЕЙКАХ, не в пикселях: пиксельный минимум разъезжается с размером
// шрифта, а живёт этот минимум ровно ради того, чтобы TUI имел куда рисовать.

/** Ниже этого TUI-агенты (Claude/Codex) перестают быть читаемыми. */
export const TERMINAL_MIN_COLS = 60;
/**
 * Высота примерно вдвое меньше ширины — так же, как человек прикидывает
 * боковой терминал: «высота примерно такая, как сейчас установлена ширина,
 * в будущем в 2 раза меньше».
 */
export const TERMINAL_MIN_ROWS = 24;

/**
 * Итоговая геометрия терминала для доступного места.
 *
 * `fit` — то, что предложил измеритель по фактическому боксу (может быть
 * `null`, если мерить пока нечего). Возвращаем и сам размер, и честный ответ
 * «влезло ли»: обрезку нужно не прятать, а называть — рядом с терминалом
 * появляется пометка, иначе уехавшая под край строка читается как баг.
 */
export function resolveTerminalGeometry(fit, min = {}) {
  const minCols = Number.isFinite(min.cols) ? Math.max(1, min.cols | 0) : TERMINAL_MIN_COLS;
  const minRows = Number.isFinite(min.rows) ? Math.max(1, min.rows | 0) : TERMINAL_MIN_ROWS;
  const fitCols = Number.isFinite(fit?.cols) ? Math.max(0, fit.cols | 0) : 0;
  const fitRows = Number.isFinite(fit?.rows) ? Math.max(0, fit.rows | 0) : 0;
  if (fitCols <= 0 || fitRows <= 0) {
    return { cols: minCols, rows: minRows, clippedX: false, clippedY: false, clipped: false };
  }
  const cols = Math.max(fitCols, minCols);
  const rows = Math.max(fitRows, minRows);
  const clippedX = cols > fitCols;
  const clippedY = rows > fitRows;
  return { cols, rows, clippedX, clippedY, clipped: clippedX || clippedY };
}
