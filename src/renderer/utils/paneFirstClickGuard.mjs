// Первый клик по НЕфокусной панели: он выбирает панель, а не нажимает то,
// что под курсором.
//
// Панель — полноценная мини-рабочая область, и в транскрипте есть элементы,
// которые «ловят» клик: блок размышлений, вывод bash, любая раскрывающаяся
// карточка. Пока панель не в фокусе, попасть по ней мышью — это в первую
// очередь «перейди сюда»; раскрытие блока при этом происходит случайно, и
// пользователь получает изменение содержимого, которого не просил.
//
// Поэтому первый клик по невыбранной панели ТОЛЬКО фокусирует её. Второй уже
// работает как обычно — панель к этому моменту выбрана, и намерение однозначно.
//
// Два исключения, оба про то, что цель клика сама по себе однозначна:
//
//   • ТЕРМИНАЛ. Клик по терминалу — это установка курсора/выделение, а не
//     раскрытие чего-то. Терминал одинаково ведёт себя и основной поверхностью,
//     и боковой, поэтому глотать здесь первый клик значит ломать привычную
//     работу с текстом.
//   • ПОЛЕ ВВОДА. Клик по инпуту — «хочу сюда писать»; съесть его значит
//     потребовать два клика перед набором текста.
//
// Всё остальное в AI-чате (транскрипт, карточки, кнопки, таймлайн) первый клик
// не получает.

/** Поверхности, которые ОБЯЗАНЫ получить даже первый клик. */
export const FIRST_CLICK_PASSTHROUGH_SELECTORS = Object.freeze([
  // Терминал — именно СЛОЙ xterm, а не рамка вокруг него: в терминальном
  // режиме рамка (`data-floating-terminal`) занимает всю панель и является
  // предком вообще всего, включая транскрипт. Указав на неё, правило
  // пропускало бы каждый клик — измерено живьём: поглощение не срабатывало
  // нигде.
  '[data-terminal-layer-tab-id]',
  '.xterm',
  // Поле ввода: сам композер AI-чата и любые нативные поля/редакторы внутри
  // панели — они всегда означают «печатать здесь».
  '[data-ai-composer-surface]',
  'textarea',
  'input',
  '[contenteditable="true"]',
  '.cm-editor',
]);

/**
 * Оверлеи, которые живут ПОВЕРХ панели и принадлежат себе, а не ей.
 *
 * Клик по меню — это работа с меню, и оно вообще может быть открыто для другой
 * панели. Глотать здесь первый клик значит ломать выбор пункта в меню.
 */
export const FIRST_CLICK_OVERLAY_SELECTORS = Object.freeze([
  '[data-tab-switcher-root]',
  '[data-pane-recent-menu]',
  '[data-tab-context-menu]',
  '[data-split-direction-menu]',
  '[data-run-after-picker-menu]',
  '[data-command-history-popover]',
  // Полосы ресайза принадлежат границе между панелями, а не панели.
  '[data-split-divider]',
]);

const matches = (el, selectors) => (
  !!el && typeof el.closest === 'function' && selectors.some((s) => !!el.closest(s))
);

/**
 * Нужно ли ПОГЛОТИТЬ этот клик (сфокусировать панель и не пускать дальше)?
 *
 * @param {object} args
 * @param {Element|null} args.target      элемент под курсором
 * @param {number} args.paneIndex         панель, по которой кликнули
 * @param {number} args.focusedIndex      панель в фокусе сейчас
 * @param {number} args.button            кнопка мыши
 * @returns {boolean}
 */
export function shouldSwallowFirstPaneClick({ target, paneIndex, focusedIndex, button = 0 }) {
  // Только левая кнопка: правая открывает меню О чём-то, средняя удаляет —
  // ни то ни другое не является «перейди в панель» (то же правило, что у
  // фокуса панели и у владельца клавиатуры).
  if (button !== 0) return false;
  // Панель уже выбрана — клик обычный.
  if (!Number.isFinite(paneIndex) || paneIndex < 0) return false;
  if (paneIndex === focusedIndex) return false;
  // Оверлеи проверяются ПЕРВЫМИ: меню панели рендерится внутри её обёртки, и
  // спросив сначала про панель, мы приняли бы клик по меню за клик по работе.
  if (matches(target, FIRST_CLICK_OVERLAY_SELECTORS)) return false;
  if (matches(target, FIRST_CLICK_PASSTHROUGH_SELECTORS)) return false;
  return true;
}
