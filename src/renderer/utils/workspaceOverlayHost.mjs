// Слой, в котором рисуются всплывающие меню рабочей области.
//
// Зачем он вообще нужен. Меню (выбор модели, effort, откат, подсказки) рисуются
// порталом — то есть их DOM-узел уезжает из того места дерева, где живёт сам
// компонент. Раньше он уезжал в КОРЕНЬ страницы, и это давало баг: при переходе
// на Home рабочая область не размонтируется, её прячут невидимостью, а узел в
// корне страницы к спрятанному поддереву не относится — меню оставались висеть
// поверх Home на своём верхнем слое.
//
// Лечится не проверкой «а не Home ли сейчас» в каждом меню — такую проверку
// пришлось бы помнить при каждом новом меню, и однажды её забудут. Лечится
// местом: узел-слой лежит ВНУТРИ рабочей области, поэтому прячется вместе с ней
// сам собой, без единого условия. Это ровно тот же приём, которым панель
// управления рисуется внутри поля ввода (composerControlsHost.mjs).
//
// Почему реестр, а не поиск по id: поиск отвечает «что существовало в этот
// момент». Узел пересоздаётся вместе со своим владельцем, и найденная однажды
// ссылка указывала бы на оторванный от документа узел — меню рисовалось бы туда,
// где его никто не увидит. Здесь владелец САМ публикует свой узел, и подписчикам
// об этом сообщают; ничего не опрашивается и не ждёт по таймеру.
//
// Слой не имеет собственной геометрии: это пустой узел без размеров. Меню внутри
// него позиционируются относительно окна сами (position: fixed), поэтому слой не
// должен ни занимать место, ни перехватывать клики. По той же причине он обязан
// лежать там, где ни один предок не создаёт систему координат для fixed
// (transform/filter/perspective/contain) — иначе меню начнут считать координаты
// от предка, а не от окна.

/** @type {Element|null} */
let host = null;
/** @type {Set<(node: Element|null) => void>} */
const listeners = new Set();

const notify = () => {
  for (const listener of listeners) listener(host);
};

/**
 * Опубликовать (или снять) слой рабочей области.
 *
 * `null` при размонтировании обязателен: без него подписчики остались бы с
 * ссылкой на оторванный узел и рисовали бы в пустоту.
 *
 * @param {Element|null} node
 */
export function setWorkspaceOverlayHost(node) {
  const next = node || null;
  if (host === next) return;
  host = next;
  notify();
}

/**
 * Снять слой, ТОЛЬКО если он всё ещё тот самый.
 *
 * Ловушка с порядком: при перестроении разметки React монтирует новый узел
 * раньше, чем размонтирует старый. Очистка «по факту размонтирования» стёрла бы
 * слой, только что опубликованный новым владельцем, и меню навсегда вернулись бы
 * в корень страницы — то есть баг вернулся бы молча.
 *
 * @param {Element|null} node
 */
export function releaseWorkspaceOverlayHost(node) {
  if (!node || host !== node) return;
  host = null;
  notify();
}

/** @returns {Element|null} */
export function getWorkspaceOverlayHost() {
  return host;
}

/**
 * @param {(node: Element|null) => void} listener
 * @returns {() => void}
 */
export function subscribeWorkspaceOverlayHost(listener) {
  if (typeof listener !== 'function') return () => {};
  listeners.add(listener);
  return () => { listeners.delete(listener); };
}

/**
 * Куда рисовать всплывающий слой.
 *
 * Возвращает корень страницы, пока слой не опубликован: меню не должно
 * исчезнуть только потому, что владелец слоя ещё не смонтирован. Это запасной
 * путь, а не равноправный — в рабочей области слой есть всегда.
 *
 * @param {Document} [doc]
 * @returns {Element}
 */
export function workspaceOverlayPortalTarget(doc = document) {
  return host || doc.body;
}
