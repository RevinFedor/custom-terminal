// Кто имеет право двигать «читаемый кусок» истории.
//
// История длинной сессии держится в памяти окном: несколько сотен записей
// вокруг того места, где человек читает, всё остальное — заглушки. Окно едет за
// видимой областью, и вопрос ровно один: КАКОЕ движение области считать
// чтением.
//
// Живой баг (18.08 01:50:31, tab-3607): переключение на вкладку заново собирает
// список, и он публикует первую видимую область — самый верх, строки 0-9 —
// ДО того, как восстановление положения увело его туда, где человек читал.
// Наблюдатель этой области поверил: попросил кусок вокруг строки 0, и ответ
// вытеснил тот кусок, в котором человек и находился. Вкладка стала серой, пока
// по ней не кликнули ещё раз.

import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import test from 'node:test';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const panel = fs.readFileSync(path.join(here, 'HistoryPanel.tsx'), 'utf8');

test('область, опубликованная во время переезда, не двигает читаемый кусок', () => {
  // Прыжок по таймлайну это уже знал; восстановление положения — тот же факт:
  // область ДВИГАЮТ, а не читают. Признак уже есть, наблюдатель его не спрашивал.
  assert.match(panel, /if \(historyJumpHydrationActiveRef\.current\) return;/);
  assert.match(
    panel,
    /if \(reason === 'range-changed' && historyRestoreInFlightRef\.current !== 0\) return;/,
  );
});

test('переезд закончился — область проверяют сразу, а не ждут прокрутки', () => {
  // Иначе восстановление, приехавшее на заглушки (его строка-якорь была
  // отредактирована), осталось бы серым до тех пор, пока человек сам не
  // прокрутит: отказ обязан сопровождаться событием «теперь можно».
  assert.match(panel, /maybeRequestHistoryHydration\('restore-settled'\)/);
  // Именно в точке, где снимается признак переезда, — иначе проверка снова
  // попадёт внутрь него и снова будет отвергнута.
  assert.match(
    panel,
    /historyRestoreInFlightRef\.current = 0;\n\s+stampHistoryMachineScrollCooldown\(\);\n\s+\/\/[\s\S]{0,700}?maybeRequestHistoryHydration\('restore-settled'\);/,
  );
});
