// «Наведение» на карточку проекта в титлбаре — без мыши.
//
// Ctrl+Q листает список, но выбранная строка живёт внутри своей панели, а
// карточка того же проекта в титлбаре в этот момент выглядит нетронутой. Для
// человека это две разные вещи на экране, хотя речь об одном проекте: юзер
// сказал прямо — «если ты подсветишь проект, это равносильно тому, что я
// навёлся на него мышью».
//
// Поэтому переключатель не рисует ничего нового, а лишь сообщает, на каком
// проекте он сейчас стоит; карточка сама показывает СВОЁ обычное наведение.
// Так подсветка не может разойтись с настоящим ховером — она и есть он.
//
// Сигнал намеренно событие, а не поле в сторе: он живёт только пока открыта
// панель, ничего не переживает и не должен ни сохраняться, ни восстанавливаться
// после перезапуска. Класть такое в store — значит хранить состояние, у
// которого нет владельца.

export const PROJECT_HOVER_PREVIEW_EVENT = 'project:hover-preview';

export interface ProjectHoverPreviewDetail {
  /** null = ни на чём (панель закрыта или выбран Home). */
  projectId: string | null;
}

export function emitProjectHoverPreview(projectId: string | null): void {
  window.dispatchEvent(
    new CustomEvent<ProjectHoverPreviewDetail>(PROJECT_HOVER_PREVIEW_EVENT, {
      detail: { projectId },
    }),
  );
}
