// Высоты верхней полосы окна — в ОДНОМ месте.
//
// Две поверхности стоят напротив этой полосы через `position: fixed` и поэтому
// не могут узнать её высоту из обычной раскладки: боковой файловый проводник и
// панель переключателя вкладок. Раньше обе носили в себе число 70 (шапка 40 +
// строка кнопок 30), и добавление строки оставляло их поверх полосы, пока
// кто-нибудь не вспомнит поправить оба числа.

/**
 * Шапка приложения: карточки проектов слева, кнопки рабочей области справа.
 *
 * Было 40 при ДВУХ строках наверху. Вторая строка (полоса кнопок во всю ширину)
 * удалена 2026-08-18: её левая половина уехала внутрь боковой панели вкладок,
 * правая — сюда, в шапку. Строка во всю ширину экрана существовала ради десятка
 * кнопок и отнимала высоту у терминала на каждом экране.
 *
 * Первая строка всегда занята кнопками окна macOS, поэтому высоту задаём тут и
 * повторяем её в `titleBarOverlay.height` главного процесса — иначе кружки
 * закрытия/сворачивания встанут не по центру строки.
 */
export const TITLE_BAR_H = 30;

/**
 * Полоска инструментов ВНУТРИ боковой панели вкладок: показать файлы проекта,
 * история вкладок, сжать логи, VS Code, GT Editor, состояние индекса.
 *
 * Живёт над списком вкладок и принадлежит тому же проекту, что и список.
 *
 * Высота считается от кнопки, а не наоборот: кнопки здесь той же меры, что
 * Docs и остальные кнопки рабочей области (26px, шрифт 11) — один размер
 * кнопки на всё приложение читается как одна система, а собственный мелкий
 * размер выглядел бы «второсортным» рядом с ними.
 */
export const SIDEBAR_TOOLS_H = 30;

/**
 * Потолок высоты карточки проекта в шапке. Отступы карточки настраиваются
 * пользователем, а строка теперь низкая — без потолка карточка вылезала бы за
 * её край. Ограничение только по вертикали: по ширине карточки свободны.
 */
export const PROJECT_CARD_MAX_H = 24;

/**
 * Рабочая директория раньше занимала здесь собственную строку во всю ширину.
 * Убрана 2026-08-17: целая строка ради одной короткой подписи несоразмерна
 * тому, что она сообщает, и отвечала только за активную вкладку — в разделённом
 * окне пути остальных панелей не показывались вовсе. Юзер: *«это нахуя кусок
 * ради вот этого вот показа? выделил целую строку»*.
 *
 * Путь теперь едет в шапке каждой панели, второй строкой под чипом вкладки
 * (SplitPaneChrome::SplitPaneAttachRow). Он принадлежит вкладке — значит, стоит
 * там, где вкладка названа, и каждая панель отвечает за себя.
 */

/** Всё, что выше рабочей области. */
export const TOP_STRIP_H = TITLE_BAR_H;

/**
 * Верхняя граница выезжающего файлового проводника.
 *
 * Проводник открывается кнопкой, которая теперь стоит в полоске инструментов
 * боковой панели. Он и начинается ровно под этой полоской: панель, вылезающая
 * поверх собственной кнопки, читается как «кнопка исчезла».
 */
export const EXPLORER_TOP_H = TITLE_BAR_H + SIDEBAR_TOOLS_H;
